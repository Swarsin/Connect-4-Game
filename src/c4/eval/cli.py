"""Evaluation command-line interface.

Examples::

    python -m c4.eval.cli play minimax:d=4 random -n 50
    python -m c4.eval.cli benchmark minimax:d=4 --file data/benchmarks/c4_mixed_test.jsonl
    python -m c4.eval.cli elo --agents random minimax:d=2 mcts:it=500 --workers 8
    python -m c4.eval.cli vs-solver az:ckpt=models/az-main-final.pt,sims=800 -n 50
    python -m c4.eval.cli report
"""

from __future__ import annotations

import argparse
import itertools
import json
import re
import statistics
import time
from pathlib import Path

from c4.eval.arena import load_games, play_match, save_games

RESULTS = Path("results")
GAMES_FILE = RESULTS / "elo" / "games.jsonl"


def safe(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.=-]+", "_", name).strip("_")


def cmd_play(a: argparse.Namespace) -> None:
    t = time.time()
    res = play_match(a.agent_a, a.agent_b, a.openings, a.n, a.seed, a.workers)
    print(res.summary(), f"[{time.time() - t:.1f}s]")
    if a.save:
        save_games(res.games, a.games_file)


def cmd_benchmark(a: argparse.Namespace) -> None:
    from c4.eval.benchmark import evaluate_spec, format_table, load_benchmark

    out_dir = RESULTS / "benchmarks"
    out_dir.mkdir(parents=True, exist_ok=True)
    for f in a.file:
        items = load_benchmark(f, a.limit)
        t = time.time()
        res = evaluate_spec(a.agent, items, a.workers)
        name = Path(f).stem
        print(f"\n{a.agent} on {name} ({len(items)} positions, {time.time() - t:.0f}s)")
        print(format_table({a.agent: res}))
        payload = {"agent": a.agent, "benchmark": name, "limit": a.limit, "results": res}
        (out_dir / f"{safe(a.agent)}__{name}.json").write_text(json.dumps(payload, indent=1))


def cmd_elo(a: argparse.Namespace) -> None:
    from c4.eval.elo import format_ratings, ratings

    games = load_games(a.games_file)
    played = {tuple(sorted((g.first, g.second))) for g in games}
    for x, y in itertools.combinations(a.agents or [], 2):
        if tuple(sorted((x, y))) in played and not a.force:
            continue
        t = time.time()
        res = play_match(x, y, a.openings, a.n, a.seed, a.workers)
        print(res.summary(), f"[{time.time() - t:.1f}s]")
        save_games(res.games, a.games_file)
        games.extend(res.games)
    if a.only:
        keep = set(a.only)
        games = [g for g in games if g.first in keep and g.second in keep]
    rs = ratings(games, anchor=a.anchor, bootstrap=a.bootstrap)
    table = format_ratings(rs)
    print("\n" + table)
    out = Path(a.games_file).parent
    (out / "ratings.json").write_text(json.dumps([r.__dict__ for r in rs], indent=1))
    (out / "ratings.md").write_text(table + "\n")


def cmd_vs_solver(a: argparse.Namespace) -> None:
    out: dict = {"agent": a.agent}
    for first in (True, False):
        if (first and not a.as_first) or (not first and not a.as_second):
            continue
        res = play_match(a.agent, "solver", ["" for _ in range(a.n)], None, a.seed, a.workers)
        games = [g for g in res.games if (g.first == a.agent) == first]
        lengths = [len(g.moves) for g in games]
        wins = sum(1 for g in games if g.winner == (1 if first else 2))
        losses = sum(1 for g in games if g.winner == (2 if first else 1))
        key = "as_first" if first else "as_second"
        out[key] = {
            "games": len(games),
            "wins": wins,
            "draws": len(games) - wins - losses,
            "losses": losses,
            "mean_length": statistics.mean(lengths) if lengths else None,
            "max_length_rate": sum(1 for x in lengths if x >= 41) / max(1, len(lengths)),
        }
        print(key, out[key])
    d = RESULTS / "vs_solver"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{safe(a.agent)}.json").write_text(json.dumps(out, indent=1))


def cmd_report(a: argparse.Namespace) -> None:
    from c4.eval.benchmark import format_table

    lines = [
        "# Results",
        "",
        "Generated by `python -m c4.eval.cli report`. Full analysis: `docs/report.md`.",
        "",
    ]
    rmd = RESULTS / "elo" / "ratings.md"
    if rmd.exists():
        lines += ["## Elo ratings (anchor: random = 0)", "", rmd.read_text(), ""]
    by_bench: dict[str, dict] = {}
    for f in sorted((RESULTS / "benchmarks").glob("*.json")):
        d = json.loads(f.read_text())
        by_bench.setdefault(d["benchmark"], {})[d["agent"]] = d["results"]
    for bench, res in sorted(by_bench.items()):
        lines += [f"## Benchmark `{bench}` (% of positions)", "", format_table(res), ""]
    vs = sorted((RESULTS / "vs_solver").glob("*.json")) if (RESULTS / "vs_solver").exists() else []
    if vs:
        lines += [
            "## Against the perfect solver",
            "",
            "| agent | as first (W/D/L) | as second (W/D/L, mean length) |",
            "|---|---|---|",
        ]
        for f in vs:
            d = json.loads(f.read_text())
            fi, se = d.get("as_first"), d.get("as_second")
            a1 = f"{fi['wins']}/{fi['draws']}/{fi['losses']}" if fi else "-"
            a2 = (
                f"{se['wins']}/{se['draws']}/{se['losses']}, {se['mean_length']:.1f}" if se else "-"
            )
            lines.append(f"| {d['agent']} | {a1} | {a2} |")
        lines.append("")
    (RESULTS / "README.md").write_text("\n".join(lines))
    print(f"wrote {RESULTS / 'README.md'}")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="c4.eval")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("play")
    p.add_argument("agent_a")
    p.add_argument("agent_b")
    p.add_argument("-n", type=int, default=None)
    p.add_argument("--openings", default="two")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--save", action="store_true")
    p.add_argument("--games-file", default=str(GAMES_FILE))
    p.set_defaults(fn=cmd_play)

    p = sub.add_parser("benchmark")
    p.add_argument("agent")
    p.add_argument("--file", nargs="+", default=["data/benchmarks/c4_mixed_test.jsonl"])
    p.add_argument("--limit", type=int, default=None)
    p.add_argument("--workers", type=int, default=8)
    p.set_defaults(fn=cmd_benchmark)

    p = sub.add_parser("elo")
    p.add_argument("--agents", nargs="*")
    p.add_argument("--only", nargs="*", help="restrict the rating fit to these agents")
    p.add_argument("-n", type=int, default=None)
    p.add_argument("--openings", default="two")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--anchor", default="random")
    p.add_argument("--bootstrap", type=int, default=200)
    p.add_argument("--force", action="store_true", help="replay pairs that already have games")
    p.add_argument("--games-file", default=str(GAMES_FILE))
    p.set_defaults(fn=cmd_elo)

    p = sub.add_parser("vs-solver")
    p.add_argument("agent")
    p.add_argument("-n", type=int, default=50, help="games per colour")
    p.add_argument("--as-first", action="store_true")
    p.add_argument("--as-second", action="store_true")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--workers", type=int, default=8)
    p.set_defaults(fn=cmd_vs_solver)

    p = sub.add_parser("report")
    p.set_defaults(fn=cmd_report)

    a = ap.parse_args(argv)
    if a.cmd == "vs-solver" and not (a.as_first or a.as_second):
        a.as_first = a.as_second = True
    a.fn(a)


if __name__ == "__main__":
    main()
